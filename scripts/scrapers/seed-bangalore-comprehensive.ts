async function main() {
  console.log("==================================================================");
  console.log("  SEEDING COMPREHENSIVE BANGALORE TECH & STARTUP ECOSYSTEM       ");
  console.log("==================================================================\n");

  // 1. Fetch Bangalore domain
  const { data: domainData, error: domainErr } = await supabase
    .from("domains")
    .select("id, tenant_id")
    .eq("slug", "bangalore")
    .single();

  if (domainErr || !domainData) {
    throw new Error(`Could not find Bangalore domain: ${domainErr?.message}`);
  }

  const domainId = domainData.id;
  const tenantId = domainData.tenant_id;

  // 2. Fetch global tech-coworking category
  const { data: globalCat, error: catErr } = await supabase
    .from("categories")
    .select("id")
    .is("domain_id", null)
    .eq("slug", "tech-coworking")
    .single();

  if (catErr || !globalCat) {
    throw new Error(`Global 'tech-coworking' category not found: ${catErr?.message}`);
  }
  const techCategoryId = globalCat.id;

  console.log(`Target Domain: bangalore (${domainId})`);
  console.log(`Tenant ID:     ${tenantId}`);
  console.log(`Category ID:   ${techCategoryId}`);
  console.log(`Companies:     ${BANGALORE_COMPANIES.length} to upsert\n`);

  let inserted = 0;
  let errors = 0;

  for (let i = 0; i < BANGALORE_COMPANIES.length; i++) {
    const co = BANGALORE_COMPANIES[i];
    const slug = slugify(co.name);

    const record = {
      tenant_id: tenantId,
      domain_id: domainId,
      category_id: techCategoryId,
      title: co.name,
      slug,
      short_description: co.short_description,
      status: "published" as const,
      website: co.website,
      careers_url: co.careers_url,
      company_type: co.company_type,
      funding_stage: co.funding_stage,
      employee_range: co.employee_range,
      founded_year: co.founded_year,
      tech_stack: co.tech_stack,
      latitude: co.lat,
      longitude: co.lng,
      address_line_1: co.address_line_1 || co.locality || "Bangalore",
      city: "Bangalore",
      locality: co.locality,
      is_featured: co.is_featured ?? false,
      updated_at: new Date().toISOString(),
    };

    const { error: upsertErr } = await supabase
      .from("listings")
      .upsert(record, { onConflict: "domain_id,slug" });

    if (upsertErr) {
      console.error(`❌ [${co.name}]:`, upsertErr.message);
      errors++;
    } else {
      inserted++;
      process.stdout.write(`✅ [${inserted}/${BANGALORE_COMPANIES.length}] ${co.name}\r`);
    }
  }

  console.log(`\n\n🎉 Done! Seeded ${inserted} Bangalore tech companies (${errors} errors).`);

  // Verification count
  const { count: blrTechCount } = await supabase
    .from("listings")
    .select("id", { count: "exact", head: true })
    .eq("domain_id", domainId)
    .not("company_type", "is", null);

  const { count: blrCareersCount } = await supabase
    .from("listings")
    .select("id", { count: "exact", head: true })
    .eq("domain_id", domainId)
    .not("careers_url", "is", null);

  console.log(`\n📊 Bangalore Database Status:`);
  console.log(`   Total Tech Listings in Bangalore: ${blrTechCount}`);
  console.log(`   Companies with Active Careers URLs: ${blrCareersCount}`);
  console.log(`\n🚀 Ready for ATS job sync.`);

  process.exit(0);
}

main().catch((err) => {
  console.error("Fatal error during seeding:", err);
  process.exit(1);
});
