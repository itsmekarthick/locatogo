function generateSlug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// 3. ATS Scraper helper
async function fetchAtsJobs(company: RealCompanyDef): Promise<any[]> {
  if (!company.ats_type || !company.ats_slug) return [];

  try {
    if (company.ats_type === "greenhouse") {
      const res = await fetch(`https://boards-api.greenhouse.io/v1/boards/${company.ats_slug}/jobs?content=true`, {
        headers: { "User-Agent": "Mozilla/5.0" },
        signal: AbortSignal.timeout(4000),
      });
      if (!res.ok) return [];
      const data = await res.json();
      return (data.jobs || []).map((j: any) => ({
        title: j.title,
        department: j.departments?.[0]?.name || "Engineering",
        location_name: j.location?.name || company.city,
        workplace_type: (j.location?.name || "").toLowerCase().includes("remote") ? "remote" : "hybrid",
        apply_url: j.absolute_url,
        posted_at: j.updated_at || new Date().toISOString(),
      }));
    } else if (company.ats_type === "ashby") {
      const res = await fetch(`https://api.ashbyhq.com/posting-api/job-board/${company.ats_slug}`, {
        headers: { "User-Agent": "Mozilla/5.0" },
        signal: AbortSignal.timeout(4000),
      });
      if (!res.ok) return [];
      const data = await res.json();
      return (data.jobs || []).map((j: any) => ({
        title: j.title,
        department: j.department || "Technology",
        location_name: j.location || company.city,
        workplace_type: j.isRemote ? "remote" : "hybrid",
        apply_url: j.jobUrl,
        posted_at: j.publishedAt || new Date().toISOString(),
      }));
    }
  } catch (err: any) {
    // ATS fetch failure is non-fatal
  }
  return [];
}

async function main() {
  console.log(`\n🚀 Ingesting ${REAL_COMPANIES.length} verified real companies across all global & Indian regions...`);

  // Cache domain map
  const { data: dbDomains } = await supabase.from("domains").select("id, slug");
  const domainIdMap = new Map<string, string>();
  for (const d of dbDomains || []) {
    domainIdMap.set(d.slug, d.id);
  }

  // Get tenant ID & category ID
  const { data: tenants } = await supabase.from("tenants").select("id").limit(1);
  const tenantId = tenants?.[0]?.id || "1c186ac3-a365-4653-bd47-b87758890dfb";

  const { data: cat } = await supabase.from("categories").select("id").eq("tenant_id", tenantId).limit(1).single();
  const categoryId = cat?.id;

  let insertedCompanies = 0;
  let insertedJobs = 0;

  for (const comp of REAL_COMPANIES) {
    const slug = generateSlug(comp.title);
    const domainId = domainIdMap.get(comp.domain_slug) || domainIdMap.get("siliconvalley");

    // Fetch real live jobs if ATS is declared
    const rawJobs = await fetchAtsJobs(comp);
    const accurateJobCount = rawJobs.length;

    const listingPayload = {
      tenant_id: tenantId,
      domain_id: domainId,
      category_id: categoryId,
      title: comp.title,
      slug: slug,
      short_description: comp.short_description,
      description: comp.short_description,
      website: comp.website,
      careers_url: comp.careers_url || comp.website,
      address_line_1: `${comp.locality}, ${comp.city}`,
      locality: comp.locality,
      city: comp.city,
      administrative_area: comp.state,
      postal_code: comp.postal_code,
      country_code: comp.country_code,
      latitude: comp.latitude,
      longitude: comp.longitude,
      status: "published",
      verification_status: "verified",
      company_type: comp.company_type,
      funding_stage: comp.funding_stage,
      employee_range: comp.employee_range,
      founded_year: comp.founded_year,
      tech_stack: comp.tech_stack,
      active_jobs_count: accurateJobCount,
      is_featured: accurateJobCount > 0,
      updated_at: new Date().toISOString(),
    };

    const { data: listing, error: lErr } = await supabase
      .from("listings")
      .upsert(listingPayload, { onConflict: "domain_id,slug" })
      .select("id")
      .single();

    if (lErr) {
      console.warn(`⚠️ Error inserting ${comp.title}:`, lErr.message);
      continue;
    }

    insertedCompanies++;

    // Insert active jobs if available
    if (listing && rawJobs.length > 0) {
      const jobRows = rawJobs.slice(0, 50).map((j) => ({
        tenant_id: tenantId,
        listing_id: listing.id,
        title: j.title,
        department: j.department,
        location_name: j.location_name,
        workplace_type: j.workplace_type,
        apply_url: j.apply_url,
        posted_at: j.posted_at,
        is_active: true,
      }));

      const { error: jErr } = await supabase.from("company_jobs").insert(jobRows);
      if (!jErr) {
        insertedJobs += jobRows.length;
      }
    }

    console.log(`✅ [${comp.city}, ${comp.country_code}] ${comp.title} (Jobs: ${accurateJobCount})`);
  }

  console.log(`\n🎉 Ingestion finished: ${insertedCompanies} real verified companies upserted, ${insertedJobs} live jobs added.`);
}

main().catch(console.error);
