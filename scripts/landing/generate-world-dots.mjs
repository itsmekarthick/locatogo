// One-off generator for src/lib/landing/world-dots.ts.
// Rasterises Natural Earth 110m land polygons (public domain, https://www.naturalearthdata.com) into a dot grid.
// Usage: node scripts/landing/generate-world-dots.mjs <path-to-ne_110m_land.geojson>
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (!input) {
  console.error("Pass the path to ne_110m_land.geojson");
  process.exit(1);
}

const LNG_MIN = -170;
const LNG_MAX = 180;
const LAT_MAX = 75;
const LAT_MIN = -45;
const STEP = 2.5;
const COLS = Math.round((LNG_MAX - LNG_MIN) / STEP);
const ROWS = Math.round((LAT_MAX - LAT_MIN) / STEP);

const geo = JSON.parse(readFileSync(input, "utf8"));
const polygons = [];
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry;
  if (type === "Polygon") polygons.push(coordinates);
  if (type === "MultiPolygon") polygons.push(...coordinates);
}

// Even-odd rule across every ring of a polygon, so holes (lakes, seas) are respected.
function inside(polygon, x, y) {
  let hit = false;
  for (const ring of polygon) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const runs = [];
for (let row = 0; row < ROWS; row++) {
  const lat = LAT_MAX - (row + 0.5) * STEP;
  let start = -1;
  for (let col = 0; col <= COLS; col++) {
    const lng = LNG_MIN + (col + 0.5) * STEP;
    const land = col < COLS && polygons.some((polygon) => inside(polygon, lng, lat));
    if (land && start < 0) start = col;
    if (!land && start >= 0) {
      runs.push(row, start, col - start);
      start = -1;
    }
  }
}

const output = `// Generated by scripts/landing/generate-world-dots.mjs from Natural Earth 110m land (public domain). Do not edit by hand.
// Each run is [row, firstColumn, length] on a ${COLS} x ${ROWS} grid of ${STEP} degree cells.
export const WORLD_DOTS = {
  lngMin: ${LNG_MIN},
  lngMax: ${LNG_MAX},
  latMax: ${LAT_MAX},
  latMin: ${LAT_MIN},
  step: ${STEP},
  cols: ${COLS},
  rows: ${ROWS},
  runs: [${runs.join(",")}],
} as const;
`;

writeFileSync(new URL("../../src/lib/landing/world-dots.ts", import.meta.url), output.replace(/\n/g, "\r\n"));
console.log(`Wrote ${runs.length / 3} runs.`);
